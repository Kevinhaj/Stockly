create or replace function public.invite_inventory_member(p_email text)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_owner_email text;
  v_invited_user_id uuid;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if char_length(v_email) < 3 or char_length(v_email) > 254 or v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'Enter a valid email address';
  end if;

  select email into v_owner_email from auth.users where id = auth.uid();
  if lower(coalesce(v_owner_email, '')) = v_email then
    raise exception 'You cannot invite your own account';
  end if;

  select id into v_invited_user_id
    from auth.users
   where lower(email) = v_email
   limit 1;
  if v_invited_user_id is null then
    raise exception 'No Stockly account uses this email address';
  end if;

  if exists (
    select 1 from public.inventory_members
     where owner_user_id = auth.uid() and member_user_id = v_invited_user_id
  ) then
    raise exception 'This account already has access to your inventory';
  end if;

  insert into public.inventory_invitations (owner_user_id, invited_user_id, invited_by)
  values (auth.uid(), v_invited_user_id, auth.uid())
  on conflict (owner_user_id, invited_user_id) do nothing;
end;
$$;


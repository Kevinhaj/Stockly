create or replace function public.ensure_user_profile()
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  insert into public.inventory_warehouses (user_id, name, is_default)
  values (auth.uid(), 'Almacén principal', true)
  on conflict (user_id, name) do nothing;

  if not exists (
    select 1 from public.inventory_warehouses
     where user_id = auth.uid() and is_default
  ) then
    update public.inventory_warehouses
       set is_default = true
     where id = (
       select id from public.inventory_warehouses
        where user_id = auth.uid()
        order by (name = 'Almacén principal') desc, created_at, id
        limit 1
     );
  end if;

  insert into public.user_profiles (user_id, email, last_sign_in_at)
    select account.id, account.email, now()
    from auth.users as account
    where account.id = auth.uid()
  on conflict (user_id) do update set
    email = excluded.email,
    last_sign_in_at = excluded.last_sign_in_at;

  if not found then
    raise exception 'Authenticated user record not found';
  end if;
end;
$$;


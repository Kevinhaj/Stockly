create or replace function public.register_stock_movement(
  p_inventory_owner_id uuid,
  p_product_id bigint,
  p_warehouse_id uuid,
  p_type text,
  p_quantity integer,
  p_note text default '',
  p_reference text default '',
  p_counterparty text default ''
)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_product public.products%rowtype;
  v_note text := coalesce(p_note, '');
  v_reference text := coalesce(p_reference, '');
  v_counterparty text := coalesce(p_counterparty, '');
  v_new_stock integer;
  v_warehouse_stock integer;
begin
  if not public.can_access_inventory(p_inventory_owner_id) then
    raise exception 'Authentication required';
  end if;

  if p_type is null or p_type not in ('in', 'out') or p_quantity is null or p_quantity <= 0 then
    raise exception 'Invalid stock movement';
  end if;

  if char_length(v_note) > 100 or char_length(v_reference) > 60 or char_length(v_counterparty) > 100 then
    raise exception 'Movement details are too long';
  end if;

  select * into v_product
    from public.products
    where id = p_product_id and user_id = p_inventory_owner_id
    for update;

  if not found then
    raise exception 'Product not found';
  end if;

  if not exists (
    select 1 from public.inventory_warehouses
     where id = p_warehouse_id and user_id = p_inventory_owner_id
  ) then
    raise exception 'Warehouse not found';
  end if;

  insert into public.product_warehouse_stock (user_id, product_id, warehouse_id, quantity)
  values (p_inventory_owner_id, p_product_id, p_warehouse_id, 0)
  on conflict (product_id, warehouse_id) do nothing;

  select quantity into v_warehouse_stock
    from public.product_warehouse_stock
   where product_id = p_product_id and warehouse_id = p_warehouse_id
   for update;

  if p_type = 'out' and v_warehouse_stock < p_quantity then
    raise exception 'Insufficient stock in the selected warehouse';
  end if;

  update public.product_warehouse_stock
     set quantity = v_warehouse_stock + case when p_type = 'in' then p_quantity else -p_quantity end,
         updated_at = now()
   where product_id = p_product_id and warehouse_id = p_warehouse_id;

  v_new_stock := v_product.stock + case when p_type = 'in' then p_quantity else -p_quantity end;

  update public.products
    set stock = v_new_stock
    where id = v_product.id and user_id = p_inventory_owner_id;

  insert into public.stock_movements
    (user_id, product_id, product_name, type, quantity, note, reference, counterparty,
     stock_before, stock_after, warehouse_id)
    values (p_inventory_owner_id, v_product.id, v_product.name, p_type, p_quantity, v_note,
      v_reference, v_counterparty, v_warehouse_stock,
      v_warehouse_stock + case when p_type = 'in' then p_quantity else -p_quantity end,
      p_warehouse_id);
end;
$$;


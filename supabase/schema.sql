create or replace function public.save_account_recovery_questions(
  p_question_one text,
  p_answer_one text,
  p_question_two text,
  p_answer_two text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, extensions, public, auth, pg_temp
as $$
declare
  v_answer_one text := regexp_replace(lower(btrim(coalesce(p_answer_one, ''))), '\s+', ' ', 'g');
  v_answer_two text := regexp_replace(lower(btrim(coalesce(p_answer_two, ''))), '\s+', ' ', 'g');
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  if p_question_one is null or p_question_two is null
     or p_question_one = p_question_two
     or p_question_one not in ('first_pet', 'birth_city', 'first_school', 'first_job', 'childhood_friend', 'favorite_teacher')
     or p_question_two not in ('first_pet', 'birth_city', 'first_school', 'first_job', 'childhood_friend', 'favorite_teacher')
     or char_length(v_answer_one) < 2 or char_length(v_answer_one) > 120
     or char_length(v_answer_two) < 2 or char_length(v_answer_two) > 120 then
    raise exception 'Invalid recovery questions';
  end if;

  insert into public.account_recovery_questions
    (user_id, question_one, answer_one_hash, question_two, answer_two_hash, updated_at)
  values (
    auth.uid(), p_question_one, crypt(v_answer_one, gen_salt('bf')),
    p_question_two, crypt(v_answer_two, gen_salt('bf')), now()
  )
  on conflict (user_id) do update set
    question_one = excluded.question_one,
    answer_one_hash = excluded.answer_one_hash,
    question_two = excluded.question_two,
    answer_two_hash = excluded.answer_two_hash,
    updated_at = excluded.updated_at;
end;
$$;


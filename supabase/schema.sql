create or replace function public.can_access_inventory(p_owner_user_id uuid)
returns boolean
language sql
stable
security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
  select coalesce(auth.uid() = p_owner_user_id, false)
    or exists (
      select 1 from public.inventory_members
       where owner_user_id = p_owner_user_id and member_user_id = auth.uid()
    );
$$;

revoke all on function public.can_access_inventory(uuid) from public, anon;
grant execute on function public.can_access_inventory(uuid) to authenticated;

do $$
declare
  v_policy record;
begin
  for v_policy in
    select schemaname, tablename, policyname
      from pg_policies
     where schemaname = 'public'
       and tablename in ('products', 'stock_movements', 'delivery_notes', 'delivery_note_items',
         'user_profiles', 'inventory_members', 'inventory_invitations', 'inventory_warehouses',
         'product_warehouse_stock')
  loop
    execute format('drop policy %I on %I.%I', v_policy.policyname, v_policy.schemaname, v_policy.tablename);
  end loop;
end;
$$;


create or replace function public.transfer_inventory_stock(
  p_inventory_owner_id uuid,
  p_product_id bigint,
  p_from_warehouse_id uuid,
  p_to_warehouse_id uuid,
  p_quantity integer
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, pg_temp
as $$
declare
  v_product public.products%rowtype;
  v_source_stock integer;
  v_destination_stock integer;
  v_source_name text;
  v_destination_name text;
  v_reference text := 'TR-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
begin
  if not public.can_access_inventory(p_inventory_owner_id) then
    raise exception 'Authentication required';
  end if;
  if p_quantity is null or p_quantity <= 0 or p_from_warehouse_id = p_to_warehouse_id then
    raise exception 'Invalid warehouse transfer';
  end if;

  select * into v_product
    from public.products
   where id = p_product_id and user_id = p_inventory_owner_id
   for update;
  if not found then
    raise exception 'Product not found';
  end if;

  select name into v_source_name
    from public.inventory_warehouses
   where id = p_from_warehouse_id and user_id = p_inventory_owner_id;
  if not found then
    raise exception 'Source warehouse not found';
  end if;
  select name into v_destination_name
    from public.inventory_warehouses
   where id = p_to_warehouse_id and user_id = p_inventory_owner_id;
  if not found then
    raise exception 'Destination warehouse not found';
  end if;

  select quantity into v_source_stock
    from public.product_warehouse_stock
   where product_id = p_product_id and warehouse_id = p_from_warehouse_id
   for update;
  if not found or v_source_stock < p_quantity then
    raise exception 'Insufficient stock in the source warehouse';
  end if;

  insert into public.product_warehouse_stock (user_id, product_id, warehouse_id, quantity)
  values (p_inventory_owner_id, p_product_id, p_to_warehouse_id, 0)
  on conflict (product_id, warehouse_id) do nothing;
  select quantity into v_destination_stock
    from public.product_warehouse_stock
   where product_id = p_product_id and warehouse_id = p_to_warehouse_id
   for update;

  update public.product_warehouse_stock
     set quantity = v_source_stock - p_quantity, updated_at = now()
   where product_id = p_product_id and warehouse_id = p_from_warehouse_id;
  update public.product_warehouse_stock
     set quantity = v_destination_stock + p_quantity, updated_at = now()
   where product_id = p_product_id and warehouse_id = p_to_warehouse_id;

  insert into public.stock_movements
    (user_id, product_id, product_name, type, quantity, note, reference, counterparty,
     stock_before, stock_after, warehouse_id)
  values
    (p_inventory_owner_id, v_product.id, v_product.name, 'out', p_quantity,
     'Transferencia entre almacenes', v_reference, v_destination_name,
     v_source_stock, v_source_stock - p_quantity, p_from_warehouse_id),
    (p_inventory_owner_id, v_product.id, v_product.name, 'in', p_quantity,
     'Transferencia entre almacenes', v_reference, v_source_name,
     v_destination_stock, v_destination_stock + p_quantity, p_to_warehouse_id);
end;
$$;


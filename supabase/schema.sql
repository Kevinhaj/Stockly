create or replace function public.verify_account_recovery_answers(
  p_email text,
  p_question_one text,
  p_answer_one text,
  p_question_two text,
  p_answer_two text
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, extensions, public, auth, pg_temp
as $$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_email_hash text;
  v_attempts integer;
  v_window_started_at timestamptz;
  v_locked_until timestamptz;
  v_answer_one_hash text;
  v_answer_two_hash text;
  v_valid boolean := false;
begin
  if char_length(v_email) < 3 or char_length(v_email) > 254 then
    return false;
  end if;

  if not exists (
    select 1 from auth.users as account
    join public.account_recovery_questions as recovery on recovery.user_id = account.id
    where lower(account.email) = v_email
  ) then
    return false;
  end if;

  v_email_hash := encode(digest(v_email, 'sha256'), 'hex');
  insert into public.account_recovery_attempts (email_hash)
    values (v_email_hash)
    on conflict (email_hash) do nothing;

  select attempts, window_started_at, locked_until
    into v_attempts, v_window_started_at, v_locked_until
    from public.account_recovery_attempts
    where email_hash = v_email_hash
    for update;

  if v_window_started_at < now() - interval '15 minutes' then
    update public.account_recovery_attempts
      set attempts = 0, window_started_at = now(), locked_until = null
      where email_hash = v_email_hash;
    v_attempts := 0;
    v_locked_until := null;
  end if;

  if v_locked_until is not null and v_locked_until > now() then
    return false;
  end if;

  select recovery.answer_one_hash, recovery.answer_two_hash
    into v_answer_one_hash, v_answer_two_hash
    from auth.users as account
    join public.account_recovery_questions as recovery on recovery.user_id = account.id
    where lower(account.email) = v_email
      and recovery.question_one = p_question_one
      and recovery.question_two = p_question_two
    limit 1;

  if found then
    v_valid :=
      crypt(regexp_replace(lower(btrim(coalesce(p_answer_one, ''))), '\s+', ' ', 'g'), v_answer_one_hash) = v_answer_one_hash
      and crypt(regexp_replace(lower(btrim(coalesce(p_answer_two, ''))), '\s+', ' ', 'g'), v_answer_two_hash) = v_answer_two_hash;
  end if;

  if v_valid then
    delete from public.account_recovery_attempts where email_hash = v_email_hash;
    return true;
  end if;

  update public.account_recovery_attempts
    set attempts = attempts + 1,
        locked_until = case when attempts + 1 >= 5 then now() + interval '15 minutes' else locked_until end
    where email_hash = v_email_hash;
  return false;
end;
$$;


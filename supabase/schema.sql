create or replace function public.create_delivery_note(
  p_inventory_owner_id uuid,
  p_customer text,
  p_note text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_delivery_id uuid := gen_random_uuid();
  v_folio text;
  v_customer text := btrim(coalesce(p_customer, ''));
  v_note text := coalesce(p_note, '');
  v_item jsonb;
  v_product public.products%rowtype;
  v_product_id bigint;
  v_warehouse_id uuid;
  v_warehouse_stock integer;
  v_quantity integer;
  v_new_stock integer;
  v_item_count bigint;
  v_unique_item_count bigint;
begin
  if not public.can_access_inventory(p_inventory_owner_id) then
    raise exception 'Authentication required';
  end if;

  if char_length(v_customer) < 1 or char_length(v_customer) > 100 or char_length(v_note) > 200 then
    raise exception 'Invalid delivery note details';
  end if;

  if p_items is null or jsonb_typeof(p_items) is distinct from 'array' then
    raise exception 'A delivery note requires between 1 and 100 items';
  end if;

  if jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 100 then
    raise exception 'A delivery note requires between 1 and 100 items';
  end if;

  if exists (
    select 1 from jsonb_array_elements(p_items) as items(item)
    where jsonb_typeof(item) <> 'object'
       or coalesce(item->>'product_id', '') !~ '^[1-9][0-9]*$'
       or coalesce(item->>'quantity', '') !~ '^[1-9][0-9]*$'
       or coalesce(item->>'warehouse_id', '') !~* '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
       or case when coalesce(item->>'quantity', '') ~ '^[1-9][0-9]*$'
         then (item->>'quantity')::numeric > 2147483647 else false end
       or case when coalesce(item->>'product_id', '') ~ '^[1-9][0-9]*$'
         then (item->>'product_id')::numeric > 9223372036854775807 else false end
  ) then
    raise exception 'Invalid delivery note item';
  end if;

  select count(*), count(distinct ((item->>'product_id')::bigint, (item->>'warehouse_id')::uuid))
    into v_item_count, v_unique_item_count
    from jsonb_array_elements(p_items) as items(item);

  if v_item_count <> v_unique_item_count then
    raise exception 'A product may only appear once in a delivery note';
  end if;

  v_folio := 'NE-' || to_char(now(), 'YYYYMMDD') || '-' ||
    upper(substr(replace(v_delivery_id::text, '-', ''), 1, 8));

  insert into public.delivery_notes (id, user_id, folio, customer, note)
  values (v_delivery_id, p_inventory_owner_id, v_folio, v_customer, v_note);

  for v_item in
    select item
      from jsonb_array_elements(p_items) as items(item)
      order by (item->>'product_id')::bigint, (item->>'warehouse_id')::uuid
  loop
    v_product_id := (v_item->>'product_id')::bigint;
    v_warehouse_id := (v_item->>'warehouse_id')::uuid;
    v_quantity := (v_item->>'quantity')::integer;

    select * into v_product
      from public.products
      where id = v_product_id and user_id = p_inventory_owner_id
      for update;

    if not found then
      raise exception 'Product not found';
    end if;

    if not exists (
      select 1 from public.inventory_warehouses
       where id = v_warehouse_id and user_id = p_inventory_owner_id
    ) then
      raise exception 'Warehouse not found';
    end if;

    insert into public.product_warehouse_stock (user_id, product_id, warehouse_id, quantity)
    values (p_inventory_owner_id, v_product_id, v_warehouse_id, 0)
    on conflict (product_id, warehouse_id) do nothing;
    select quantity into v_warehouse_stock
      from public.product_warehouse_stock
     where product_id = v_product_id and warehouse_id = v_warehouse_id
     for update;
    if v_warehouse_stock < v_quantity then
      raise exception 'Insufficient stock for product % in the selected warehouse', v_product.name;
    end if;

    update public.product_warehouse_stock
       set quantity = v_warehouse_stock - v_quantity, updated_at = now()
     where product_id = v_product_id and warehouse_id = v_warehouse_id;

    v_new_stock := v_product.stock - v_quantity;

    update public.products
      set stock = v_new_stock
      where id = v_product.id and user_id = p_inventory_owner_id;

    insert into public.delivery_note_items
      (delivery_note_id, product_id, product_name, sku, quantity, unit_price, warehouse_id)
      values (v_delivery_id, v_product.id, v_product.name, v_product.sku, v_quantity, v_product.price, v_warehouse_id);

    insert into public.stock_movements
      (user_id, product_id, product_name, type, quantity, note, reference, counterparty,
       stock_before, stock_after, warehouse_id)
      values (p_inventory_owner_id, v_product.id, v_product.name, 'out', v_quantity,
        v_note, v_folio, v_customer, v_warehouse_stock, v_warehouse_stock - v_quantity, v_warehouse_id);
  end loop;

  return jsonb_build_object('id', v_delivery_id, 'folio', v_folio);
end;
$$;


create or replace function public.remove_inventory_member(p_member_user_id uuid)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
begin
  if auth.uid() is null or p_member_user_id = auth.uid() then
    raise exception 'Invalid inventory member';
  end if;
  delete from public.inventory_members
   where owner_user_id = auth.uid() and member_user_id = p_member_user_id;
  delete from public.inventory_invitations
   where owner_user_id = auth.uid() and invited_user_id = p_member_user_id;
  if not found and not exists (
    select 1 from public.inventory_members
     where owner_user_id = auth.uid() and member_user_id = p_member_user_id
  ) then
    return;
  end if;
end;
$$;


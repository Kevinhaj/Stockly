create or replace function public.accept_inventory_invitation(p_owner_user_id uuid)
returns void
language plpgsql
security definer
set search_path = pg_catalog, public, auth, pg_temp
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if not exists (
    select 1 from public.inventory_invitations
     where owner_user_id = p_owner_user_id and invited_user_id = auth.uid()
  ) then
    raise exception 'This inventory invitation is no longer available';
  end if;

  insert into public.inventory_members (owner_user_id, member_user_id)
  values (p_owner_user_id, auth.uid())
  on conflict (owner_user_id, member_user_id) do nothing;

  delete from public.inventory_invitations
   where owner_user_id = p_owner_user_id and invited_user_id = auth.uid();
end;
$$;


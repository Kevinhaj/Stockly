do $$
declare
  v_id_type text;
begin
  select format_type(attribute.atttypid, attribute.atttypmod)
    into v_id_type
    from pg_attribute as attribute
   where attribute.attrelid = 'public.products'::regclass
     and attribute.attname = 'id'
     and not attribute.attisdropped;

  if v_id_type <> 'bigint' then
    raise exception 'Stockly expects public.products.id to be bigint, but found %. Keep the existing product ID type and matching product_id types in related tables before applying this schema.', coalesce(v_id_type, 'missing');
  end if;
end;
$$;


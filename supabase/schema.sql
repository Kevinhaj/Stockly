do $$
declare
  v_table text;
  v_unassigned_rows bigint;
  v_user_count bigint;
  v_user_id uuid;
begin
  foreach v_table in array array['products', 'stock_movements', 'delivery_notes']
  loop
    if to_regclass(format('public.%I', v_table)) is null then
      continue;
    end if;

    execute format(
      'alter table public.%I add column if not exists user_id uuid references auth.users (id) on delete cascade',
      v_table
    );

    execute format('select count(*) from public.%I where user_id is null', v_table)
      into v_unassigned_rows;

    if v_unassigned_rows > 0 then
      select count(*) into v_user_count from auth.users;
      if v_user_count <> 1 then
        raise exception
          'Cannot safely assign % existing rows in public.%: found % Auth accounts. Assign user_id to the correct account for these existing rows, then rerun schema.sql.',
          v_unassigned_rows, v_table, v_user_count;
      end if;

      select id into v_user_id from auth.users limit 1;
      execute format('update public.%I set user_id = $1 where user_id is null', v_table)
        using v_user_id;
    end if;

    execute format('alter table public.%I alter column user_id set default auth.uid()', v_table);
    execute format('alter table public.%I alter column user_id set not null', v_table);
  end loop;
end;
$$;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  sku text not null default '' check (char_length(sku) <= 40),
  category text not null default '' check (char_length(category) <= 40),
  price numeric(12, 2) not null default 0 check (price >= 0),
  cost numeric(12, 2) not null default 0 check (cost >= 0),
  stock integer not null default 0 check (stock >= 0),
  minimum integer not null default 5 check (minimum >= 0),
  created_at timestamptz not null default now()
);

